import logging
from collections.abc import Callable

from pydantic import ValidationError

from .grounding import ground
from .llm import chat
from .schema import Answer, Document

MAX_ATTEMPTS = 3

SYSTEM_PROMPT = """\
Ты извлекаешь данные из текста документа (счёт, коммерческое предложение, акт) и возвращаешь JSON по схеме.

Главное правило: поле заполняется, только если значение прямо написано в документе. Нет в документе — null. Ничего не додумывай и не вычисляй.

Поля:
- doc_type: invoice — счёт на оплату, счёт-фактура (шот, шот-фактура); commercial_offer — коммерческое предложение (коммерциялық ұсыныс); act — акт; всё остальное — unknown. Тип определяй по названию документа, а не по его номеру.
- supplier_name: поставщик, исполнитель или отправитель — название как в документе, вместе с формой собственности (ТОО, ЖШС, ИП). Покупателя и заказчика не бери.
- supplier_bin: БИН (БСН, ИИН) поставщика, перепиши его в точности как в документе. БИН заказчика, VAT ID и другие идентификаторы не подходят.
- doc_number: номер документа без знака «№».
- doc_date: дата составления документа в формате ГГГГ-ММ-ДД (12.11.2026 — это 2026-11-12). Срок действия, срок оплаты и другие даты — не дата документа. Даты нет — null, сегодняшнюю не подставляй.
- currency: валюта сумм документа (тенге, тг, теңге — KZT). Сумм нет — null.
- total_amount: итоговая сумма к оплате, с НДС, если он выделен. Сумму прописью переведи в число. Итог не написан — null, позиции сам не складывай.
- vat_amount: сумма НДС (ҚҚС), только если она написана числом. «Без НДС», «НДС не облагается» или указана только ставка — null. Сам НДС не считай.
- line_items: позиции документа. name — как в документе; qty и price (цена за единицу) — только если указаны, иначе null. Цену из суммы не вычисляй.

Особые случаи:
- Противоречие — две разные даты документа или две разные итоговые суммы, в том числе когда сумма цифрами не совпадает с суммой прописью: возьми значение, которое встречается в тексте первым, и на каждое противоречие добавь в warnings строку с обоими значениями. «Итого» без НДС и «Всего к оплате» с НДС — не противоречие.
- Название поставщика или позиции продублировано на двух языках через «/» — бери первый вариант.
- Ошибки OCR в цифрах (l или I вместо 1, O вместо 0): в датах и суммах исправляй только такие однозначные замены и добавляй warning. БИН не исправляй и не обнуляй из-за букв на месте цифр: перепиши как есть, читаемость проверит программа.
- Пробелы между разрядами (186 180) — обычная запись числа, а не ошибка.
- warnings — только про противоречия и про исправленные или нечитаемые значения. Таких случаев нет — пустой список. Отсутствие поля, перевод суммы из прописи в число, приведение даты к формату — не повод для warning.

field_confidence: для каждого поля уверенность от 0 до 1 в том, что его значение (в том числе null) верно.
"""

LLM = Callable[[list[dict]], str]


def extract(text: str, llm: LLM = chat) -> Document:
    if not text.strip():
        return Document.empty("документ пуст, извлекать нечего")

    messages = [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": text}]
    for attempt in range(1, MAX_ATTEMPTS + 1):
        raw = llm(messages)
        try:
            answer = Answer.model_validate_json(raw)
        except ValidationError as error:
            logging.warning("попытка %d: ответ модели не прошёл валидацию:\n%s", attempt, error)
            messages += [
                {"role": "assistant", "content": raw},
                {"role": "user", "content": f"Ответ не прошёл валидацию:\n{error}\nВерни исправленный JSON."},
            ]
        else:
            return ground(answer, text)
    return Document.empty(f"ответ модели не прошёл валидацию за {MAX_ATTEMPTS} попытки, нужен ручной разбор")
